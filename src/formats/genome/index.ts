/**
 * Genome Main — Orchestrates code generation from definitions.
 *
 * Run: tsx src/formats/genome/index.ts
 */

import { writeFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

import { generatePrimitives } from './primitives';
import { generateEnums } from './enums';
import { generateConstants } from './constants';
import { generateBasicSchemas } from './schemas/basic';
import { generateFormalizationSchemas } from './schemas/formalization';
import { generateOracleSchemas } from './schemas/oracle';
import { generateKernelSchemas } from './schemas/kernel';
import { generateGateSchemas } from './schemas/gates';
import { generateGovernanceSchemas } from './schemas/governance';
import { generateRuleSchemas } from './schemas/rules';
import { generateEventBaseSchemas } from './schemas/events/base';
import { generateCognitiveEventSchemas } from './schemas/events/cognitive';
import { generateNarEventSchemas } from './schemas/events/nar';
import { generateProposalEventSchemas } from './schemas/events/proposal';
import { generateBudgetSchemas } from './schemas/budget';
import { generateUnionSchemas } from './schemas/unions';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_DIR = join(__dirname, '..', '..', 'generated');

mkdirSync(OUT_DIR, { recursive: true });

function generate(): string {
  const lines: string[] = [];

  lines.push('// Generated by src/formats/genome/index.ts — DO NOT EDIT');
  lines.push('// Run: tsx src/formats/genome/index.ts');
  lines.push('');
  lines.push("import { z } from 'zod';");
  lines.push("import { generateId } from '@senars/util/id';");
  lines.push('');

  // Primitives
  lines.push(...generatePrimitives());

  // Enums
  lines.push(...generateEnums());

  // Constants
  lines.push(...generateConstants());

  // Schemas in dependency order
  lines.push(...generateBasicSchemas());
  lines.push(...generateFormalizationSchemas());
  lines.push(...generateOracleSchemas());
  lines.push(...generateKernelSchemas());
  lines.push(...generateGateSchemas());
  lines.push(...generateGovernanceSchemas());
  lines.push(...generateRuleSchemas());
  lines.push(...generateEventBaseSchemas());
  lines.push(...generateCognitiveEventSchemas());
  lines.push(...generateNarEventSchemas());
  lines.push(...generateProposalEventSchemas());
  lines.push(...generateBudgetSchemas());
  lines.push(...generateUnionSchemas());

  return lines.join('\n');
}

// ============================================================================
// MAIN
// ============================================================================

const output = generate();
writeFileSync(join(OUT_DIR, 'schemas.ts'), output);
console.log('Generated:', join(OUT_DIR, 'schemas.ts'));

