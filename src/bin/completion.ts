/**
 * `senars completion` — Generate shell completions for bash, zsh, fish, PowerShell.
 */

import type { CommonFlags, HelpSection } from './lib/cli-utils';
import { runCLI, standardSections } from './lib/cli-utils';
import { listCommands, getCommand } from './lib/cli';

