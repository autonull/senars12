interface Violation {
  readonly at: string;
  readonly rule: string;
  readonly detail: string;
}

interface Section {
  readonly file: string;
  readonly level: number;
  readonly heading: string;
  readonly body: string;
}

const slugify = (heading: string): string =>
  heading
    .replace(/[`*]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const readSection = (file: string): Section => {
  const [first = '', ...rest] = readFileSync(join(DIR, file), 'utf8').trimEnd().split('\n');
  const heading = /^(#{1,6}) (.+)$/.exec(first);
  if (!heading?.[2]) throw new Error(`${file} does not open with a markdown heading`);
  return {
    file,
    level: heading[1]?.length ?? 1,
    heading: heading[2],
    body: rest.join('\n').trim(),
  };
};

const sections = (): Section[] => ORDER.map(readSection);

/** A section as the README renders it: its heading, its body, every directive resolved. */
const renderSection = (section: Section): string =>
  `${'#'.repeat(section.level)} ${section.heading}${section.body ? `\n\n${section.body}` : ''}`.replace(
    /^<!-- ([a-z][\w-]*) -->$/gm,
    (_directive, name: string) => {
      const template = TEMPLATES[name];
      if (!template) throw new Error(`${section.file}: no template named '${name}'`);
      return template();
    }
  );

/** The composed README: banner, then each section, `---` between the top-level ones. */
export const buildReadme = (): string => {
  const ordered = sections();
  const blocks: string[] = [];
  for (const [index, section] of ordered.entries()) {
    if (index > 0 && section.level <= 2) blocks.push('---');
    blocks.push(renderSection(section));
  }
  return `${[BANNER, ...blocks].join('\n\n')}\n`;
};

const sectionViolations = (): Violation[] => {
  const violations: Violation[] = [];
  const listed = new Set<string>(ORDER);
  for (const file of readdirSync(DIR)) {
    if (file.endsWith('.md') && !listed.has(file)) {
      violations.push({ at: file, rule: 'orphaned-section', detail: 'not in ORDER' });
    }
  }
  let level = 0;
  for (const file of ORDER) {
    if (!existsSync(join(DIR, file))) {
      violations.push({ at: file, rule: 'missing-section', detail: 'in ORDER, absent on disk' });
      continue;
    }
    const section = readSection(file);
    const expected = file === TITLE ? section.file : `${slugify(section.heading)}.md`;
    if (expected !== file) {
      violations.push({
        at: file,
        rule: 'section-name',
        detail: `'${section.heading}' belongs in ${expected}`,
      });
    }
    if (section.level > level + 1) {
      violations.push({
        at: file,
        rule: 'heading-level',
        detail: `h${section.level} under h${level} — a section may not skip a level`,
      });
    }
    level = section.level;
  }
  return violations;
};

const linkViolations = (markdown: string): Violation[] =>
  [...markdown.matchAll(/\]\(([^)\s]+?)(?:\s+"[^"]*")?\)/g)]
    .map((match) => match[1] ?? '')
    .filter((href) => href !== '' && !/^[a-z][\w+.-]*:/i.test(href) && !href.startsWith('#'))
    .filter((href) => !existsSync(fromRoot(decodeURIComponent(href.split('#')[0] ?? ''))))
    .map((href) => ({ at: 'README.md', rule: 'dead-link', detail: href }));

const scriptViolations = (markdown: string): Violation[] => {
  const scripts = new Set(
    Object.keys(JSON.parse(readFileSync(fromRoot('package.json'), 'utf8')).scripts ?? {})
  );
  return [...markdown.matchAll(/\bpnpm\s+(?:run\s+)?([a-zA-Z][\w:.-]*)/g)]
    .map((match) => match[1] ?? '')
    .filter((name) => !name.startsWith('-') && !name.startsWith('.') && !PNPM_VERBS.has(name))
    .filter((name) => !scripts.has(name))
    .map((name) => ({ at: 'README.md', rule: 'unknown-script', detail: `pnpm ${name}` }));
};

const firstDifference = (current: string, next: string): number => {
  const a = current.split('\n');
  const b = next.split('\n');
  const index = a.findIndex((line, at) => line !== b[at]);
  return index < 0 ? Math.min(a.length, b.length) + 1 : index + 1;
};

const report = (violations: readonly Violation[]): never => {
  console.error(`readme FAILED — ${violations.length} violation(s)`);
  for (const { at, rule, detail } of violations) console.error(`  ${at}: ${rule} — ${detail}`);
  process.exit(1);
};

const main = (): void => {
  const structural = sectionViolations();
  if (structural.length > 0) report(structural);

  const next = buildReadme();
  const content = [...linkViolations(next), ...scriptViolations(next)];
  if (content.length > 0) report(content);

  const current = readFileSync(README, 'utf8');
  if (current === next) {
    console.log(
      `readme ok — ${ORDER.length} sections · ${BUILTIN_DECLARATIONS.length} rule declarations`
    );
    return;
  }
  if (process.argv.includes('--check')) {
    console.error(
      `readme:check FAILED — README.md differs from the sections at line ${firstDifference(current, next)}; run \`pnpm readme\``
    );
    process.exit(1);
  }
  writeFileSync(README, next);
  console.log(
    `readme — README.md ${ORDER.length} sections, ${next.split('\n').length} lines · ${BUILTIN_DECLARATIONS.length} rule declarations`
  );
};

if (process.argv[1]?.endsWith('generate.ts')) main();
