/**
 * Tests for the schema genome generator.
 *
 * Verifies that:
 * 1. The generator runs without errors
 * 2. Generated schemas are valid TypeScript
 * 3. Generated schemas contain all expected types
 * 4. No duplicate declarations exist
 */

import { describe, it, expect, beforeAll } from 'vitest';
import { execSync } from 'child_process';
import { readFileSync, existsSync } from 'fs';
import { join } from 'path';

const ROOT = join(__dirname, '..', '..');
const GENOME = join(ROOT, 'src', 'formats', 'genome.ts');
const GENERATED = join(ROOT, 'src', 'generated', 'schemas.ts');

describe('Schema Genome Generator', () => {
  beforeAll(() => {
    // Ensure generated file exists
    if (!existsSync(GENERATED)) {
      execSync('pnpm tsx src/formats/genome.ts', { cwd: ROOT, stdio: 'inherit' });
    }
  });

  it('should generate schemas.ts without errors', () => {
    expect(existsSync(GENERATED)).toBe(true);
    const content = readFileSync(GENERATED, 'utf-8');
    expect(content.length).toBeGreaterThan(1000);
    expect(content).toContain('// Generated by src/formats/genome.ts');
  });

  it('should contain all primitive validators', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    expect(content).toContain('export const uuid = () => z.string().uuid();');
    expect(content).toContain('export const nonEmpty = () => z.string().min(1);');
    expect(content).toContain('export const nonNegativeInt = () => z.number().int().nonnegative();');
    expect(content).toContain('export const positiveInt = () => z.number().int().positive();');
    expect(content).toContain('export const unitInterval = () => z.number().min(0).max(1);');
    expect(content).toContain('export const signedUnitInterval = () => z.number().min(-1).max(1);');
    expect(content).toContain('export const timestamp = () => z.number().int().positive();');
  });

  it('should contain all enum declarations', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    // Task types
    expect(content).toContain('export const TASK_TYPES = [');
    expect(content).toContain('export type TASK_TYPE = (typeof TASK_TYPES)[number];');
    // Source quality
    expect(content).toContain('export const SOURCE_QUALITY = [');
    expect(content).toContain('export type SOURCE_QUALITY = (typeof SOURCE_QUALITY)[number];');
    // Ambiguity
    expect(content).toContain('export const AMBIGUITY_TYPES = [');
    expect(content).toContain('export type AMBIGUITY_TYPE = (typeof AMBIGUITY_TYPES)[number];');
    expect(content).toContain('export const AMBIGUITY_SEVERITIES = [');
    expect(content).toContain('export type AMBIGUITY_SEVERITY = (typeof AMBIGUITY_SEVERITIES)[number];');
    // Stimulus sources
    expect(content).toContain('export const STIMULUS_SOURCES = [');
    expect(content).toContain('export type STIMULUS_SOURCE = (typeof STIMULUS_SOURCES)[number];');
    // Autonomy
    expect(content).toContain('export const AUTONOMY_MODES = [');
    expect(content).toContain('export type AUTONOMY_MODE = (typeof AUTONOMY_MODES)[number];');
    // Risk levels
    expect(content).toContain('export const RISK_LEVELS = [');
    expect(content).toContain('export type RISK_LEVEL = (typeof RISK_LEVELS)[number];');
    // Proposal
    expect(content).toContain('export const PROPOSAL_KINDS = [');
    expect(content).toContain('export type PROPOSAL_KIND = (typeof PROPOSAL_KINDS)[number];');
    // Budget
    expect(content).toContain('export const BUDGET_SCOPE_IDS = [');
    expect(content).toContain('export type BUDGET_SCOPE_ID = (typeof BUDGET_SCOPE_IDS)[number];');
    expect(content).toContain('export const BUDGET_TYPES = [');
    expect(content).toContain('export type BUDGET_TYPE = (typeof BUDGET_TYPES)[number];');
    expect(content).toContain('export const TERMINATION_REASONS = [');
    expect(content).toContain('export type TERMINATION_REASON = (typeof TERMINATION_REASONS)[number];');
    // Gate names
    expect(content).toContain('export const GATE_NAMES = [');
    expect(content).toContain('export type GATE_NAME = (typeof GATE_NAMES)[number];');
  });

  it('should contain all constant declarations', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    expect(content).toContain('export const TASK_PUNCTUATION = {');
    expect(content).toContain('export const SOURCE_QUALITY_CONFIDENCE = {');
    expect(content).toContain('export const AMBIGUITY_SEVERITY = {');
    expect(content).toContain('export const PROPOSAL_RISK = {');
    expect(content).toContain('export const BUDGET_TYPES_MAP = {');
    expect(content).toContain('export const NON_EXECUTING_MODES = ');
    expect(content).toContain('export const BUILTIN_RULE_ARTIFACT_VERSION = ');
    expect(content).toContain('export const RULE_TABLE_SCHEMA_VERSION = ');
    expect(content).toContain('export const PROPOSAL_SCHEMA_VERSION = ');
  });

  it('should contain key Zod schemas', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    // Truth
    expect(content).toContain('export const TruthValueSchema = z.object({');
    expect(content).toContain('export type TruthValue = z.infer<typeof TruthValueSchema>;');
    // SourceQuality
    expect(content).toContain('export const SourceQualitySchema = z.enum(SOURCE_QUALITY);');
    // Formalization
    expect(content).toContain('export const AmbiguityReportSchema = z.object({');
    expect(content).toContain('export const FormalizationCandidateSchema = z.object({');
    expect(content).toContain('export const FormalizationBatchSchema = z.object({');
    // Gates
    expect(content).toContain('export const PerceptionGateInputSchema = z.object({');
    expect(content).toContain('export const ActionGateInputSchema = z.object({');
    expect(content).toContain('export const RewardGateInputSchema = z.object({');
    expect(content).toContain('export const BudgetGateInputSchema = z.object({');
    // Governance
    expect(content).toContain('export const PatchProposalSchema = z.object({');
    expect(content).toContain('export const SelfImprovementProposalSchema = z.object({');
    // Rule table
    expect(content).toContain('export const RuleProvenanceSchema = z.discriminatedUnion');
    expect(content).toContain('export const RuleDeclarationSchema = z.object({');
    expect(content).toContain('export const RuleTableSchema = z.object({');
    // Events
    expect(content).toContain('export const CognitiveEventBaseSchema = z.object({');
    expect(content).toContain('export const TaskAdmittedEventSchema = CognitiveEventBaseSchema.extend({');
    expect(content).toContain('export const DerivationAcceptedEventSchema = CognitiveEventBaseSchema.extend({');
    // Proposals
    expect(content).toContain('export const ContentProposalSchema = EnvelopeSchema.extend({');
    expect(content).toContain('export const RuleProposalSchema = EnvelopeSchema.extend({');
    expect(content).toContain('export const ProposalSchema = z.discriminatedUnion');
    // Derivation records
    expect(content).toContain('export const DerivationStepSchema = z.object({');
    expect(content).toContain('export const DerivationRecordSchema = z.object({');
    // Budget
    expect(content).toContain('export const ReasoningBudgetSchema = z.object({');
    // Union
    expect(content).toContain('export const CognitiveEventSchema = z.discriminatedUnion');
    expect(content).toContain('export type CognitiveEvent = z.infer<typeof CognitiveEventSchema>;');
  });

  it('should not have duplicate const declarations', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    // Check for duplicate const declarations (not type declarations)
    const lines = content.split('\n');
    const declarations = new Map<string, number>();
    
    for (const line of lines) {
      const match = line.match(/^export const\s+(\w+)/);
      if (match) {
        const name = match[1] as string;
        declarations.set(name, (declarations.get(name) ?? 0) + 1);
      }
    }
    
    // These should only appear once as const declarations
    const shouldBeUnique = [
      'TASK_PUNCTUATION',
      'SOURCE_QUALITY_CONFIDENCE',
      'AMBIGUITY_SEVERITY',
      'PROPOSAL_RISK',
      'BUDGET_TYPES_MAP',
      'BUILTIN_RULE_ARTIFACT_VERSION',
      'RULE_TABLE_SCHEMA_VERSION',
      'PROPOSAL_SCHEMA_VERSION',
      'TERMINATION_REASONS',
      'BUDGET_TYPES',
      'PROPOSAL_REJECTIONS',
      'RULE_CATEGORIES',
      'KERNEL_CONTROL_STATES',
      'STIMULUS_SOURCES',
    ];
    
    for (const name of shouldBeUnique) {
      const count = declarations.get(name) ?? 0;
      expect(count).toBeLessThanOrEqual(1);
    }
  });

  it('should have TerminationReasonSchema declared before BudgetGateOutputSchema', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    const termReasonIndex = content.indexOf('export const TerminationReasonSchema');
    const budgetGateOutputIndex = content.indexOf('export const BudgetGateOutputSchema');
    
    expect(termReasonIndex).toBeGreaterThan(-1);
    expect(budgetGateOutputIndex).toBeGreaterThan(-1);
    expect(termReasonIndex).toBeLessThan(budgetGateOutputIndex);
  });

  it('should have ReasoningBudgetSchema declared before BudgetGateInputSchema', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    const reasoningBudgetIndex = content.indexOf('export const ReasoningBudgetSchema');
    const budgetGateInputIndex = content.indexOf('export const BudgetGateInputSchema');
    
    expect(reasoningBudgetIndex).toBeGreaterThan(-1);
    expect(budgetGateInputIndex).toBeGreaterThan(-1);
    expect(reasoningBudgetIndex).toBeLessThan(budgetGateInputIndex);
  });

  it('should have TaskAdmittedEventSchema declared before PerceptionGateOutputSchema', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    const taskAdmittedIndex = content.indexOf('export const TaskAdmittedEventSchema');
    const perceptionGateOutputIndex = content.indexOf('export const PerceptionGateOutputSchema');
    
    expect(taskAdmittedIndex).toBeGreaterThan(-1);
    expect(perceptionGateOutputIndex).toBeGreaterThan(-1);
    expect(taskAdmittedIndex).toBeLessThan(perceptionGateOutputIndex);
  });

  it('should have DerivationRecordSchema declared before DerivationRecordEventSchema', () => {
    const content = readFileSync(GENERATED, 'utf-8');
    const derivationRecordIndex = content.indexOf('export const DerivationRecordSchema');
    const derivationRecordEventIndex = content.indexOf('export const DerivationRecordEventSchema');
    
    expect(derivationRecordIndex).toBeGreaterThan(-1);
    expect(derivationRecordEventIndex).toBeGreaterThan(-1);
    expect(derivationRecordIndex).toBeLessThan(derivationRecordEventIndex);
  });

  it('should compile without TypeScript errors', () => {
    // This is implicitly tested by the typecheck script - just verify the file exists and is valid TS
    const content = readFileSync(GENERATED, 'utf-8');
    expect(content).toContain('export const TruthValueSchema');
    expect(content).toContain('export type CognitiveEvent');
    // The actual typecheck is run as part of the CI pipeline
  });
});