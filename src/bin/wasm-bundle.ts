#!/usr/bin/env tsx
/**
 * Single-file WASM Bundle Generator — SeNARS edge deployment.
 *
 * Generates a single JavaScript file that bundles all WASM modules
 * (z3, clingo, minisat, head bundles) as base64-encoded strings.
 * No external binaries, no containers, no Python required.
 */

import { promises as fs } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import glob from 'glob';

const __dirname = dirname(fileURLToPath(import.meta.url));

/**
 * WASM module definition for bundling.
 */
export interface WasmModuleDef {
  /** Module identifier. */
  id: string;
  /** Glob pattern to find the .wasm file. */
  glob: string;
  /** Whether this module is required (throws if missing). */
  required: boolean;
  /** Human-readable name. */
  name: string;
}

/**
 * Default WASM modules to bundle.
 */
export const DEFAULT_WASM_MODULES: WasmModuleDef[] = [
  { id: 'z3', glob: 'node_modules/.pnpm/z3-solver@*/node_modules/z3-solver/build/z3-built.wasm', required: false, name: 'Z3 Theorem Prover' },
  { id: 'clingo', glob: 'node_modules/.pnpm/clingo-wasm@*/node_modules/clingo-wasm/dist/clingo.wasm', required: false, name: 'Clingo ASP Solver' },
  { id: 'minisat', glob: 'node_modules/.pnpm/logic-solver-plus@*/node_modules/logic-solver-plus/lte-exp/repo/minisat.wasm', required: false, name: 'MiniSat SAT Solver' },
];

/**
 * Resolve glob pattern to actual file path.
 */
function resolveWasmPath(globPattern: string): string | null {
  try {
    const matches = glob.sync(globPattern, { absolute: true });
    return matches[0] ?? null;
  } catch {
    return null;
  }
}

/**
 * Read a WASM file and return base64-encoded string.
 */
async function readWasmBase64(wasmPath: string): Promise<string | null> {
  try {
    const buffer = await fs.readFile(wasmPath);
    return buffer.toString('base64');
  } catch {
    return null;
  }
}

/**
 * Generate the single-file WASM bundle.
 */
export async function generateWasmBundle(
  modules: WasmModuleDef[] = DEFAULT_WASM_MODULES,
  outputPath: string = 'dist/wasm-bundle'
): Promise<void> {
  console.log('Generating single-file WASM bundle...');

  const bundleParts: string[] = [
    '/**',
    ' * SeNARS WASM Bundle — Single-file WASM module loader.',
    ' * Auto-generated by wasm-bundle.ts. Do not edit manually.',
    ' * Run: pnpm wasm:bundle',
    ' */',
    '',
    'const MODULES = [',
  ];

  let hasAnyModule = false;

  for (const mod of modules) {
    const fullPath = resolveWasmPath(mod.glob);
    const base64 = fullPath ? await readWasmBase64(fullPath) : null;

    if (base64) {
      hasAnyModule = true;
      bundleParts.push(`  { id: '${mod.id}', name: '${mod.name}', base64: \`${base64}\`, bytes: null },`);
      console.log(`  ✓ ${mod.name} (${mod.id}) - ${Math.round(base64.length * 3 / 4 / 1024)} KB`);
    } else if (mod.required) {
      throw new Error(`Required WASM module not found: ${mod.glob}`);
    } else {
      console.log(`  ⚠ ${mod.name} (${mod.id}) - not found at ${mod.glob}, skipping`);
    }
  }

  if (!hasAnyModule) {
    console.warn('No WASM modules found. Bundle will contain empty loader.');
    bundleParts.push('  // No modules found');
  }

  bundleParts.push(
    '];',
    '',
    'let loadedModules = new Map();',
    '',
    'export async function loadWasmModule(id) {',
    '  if (loadedModules.has(id)) return loadedModules.get(id);',
    '',
    '  const mod = MODULES.find(m => m.id === id);',
    '  if (!mod) throw new Error(`WASM module not found in bundle: ${id}`);',
    '',
    '  // Convert base64 to Uint8Array',
    '  const binaryString = atob(mod.base64);',
    '  const bytes = new Uint8Array(binaryString.length);',
    '  for (let i = 0; i < binaryString.length; i++) {',
    '    bytes[i] = binaryString.charCodeAt(i);',
    '  }',
    '  mod.bytes = bytes;',
    '',
    '  const module = await WebAssembly.compile(bytes);',
    '  loadedModules.set(id, module);',
    '  return module;',
    '}',
    '',
    'export async function instantiateWasmModule(id, imports) {',
    '  const module = await loadWasmModule(id);',
    '  return await WebAssembly.instantiate(module, imports);',
    '}',
    '',
    'export function listWasmModules() {',
    '  return MODULES.map(m => m.id);',
    '}',
    '',
    'export function getWasmModuleInfo(id) {',
    '  return MODULES.find(m => m.id === id);',
    '}',
    '',
    '// Auto-load all modules on import (optional, comment out for lazy loading)',
    '// MODULES.forEach(m => loadWasmModule(m.id).catch(() => {}));',
    '',
    'export default { loadWasmModule, instantiateWasmModule, listWasmModules, getWasmModuleInfo };',
  );

  const outputDir = dirname(outputPath);
  await fs.mkdir(outputDir, { recursive: true });
  await fs.writeFile(outputPath, bundleParts.join('\n'), 'utf8');

  console.log(`\n✓ WASM bundle written to ${outputPath}`);
  console.log(`  Modules: ${modules.filter(m => m.required || true).length} total, ${modules.length} configured`);
}

/**
 * CLI entry point.
 */
async function main(): Promise<void> {
  const args = process.argv.slice(2);

  if (args.includes('--help')) {
    console.log(`
WASM Bundle Generator

Usage: pnpm wasm:bundle [options]

Options:
  --output <path>      Output file path (default: dist/wasm-bundle.js)
  --include <ids>      Comma-separated module IDs to include (default: z3,clingo,minisat)
  --help               Show this help

Examples:
  pnpm wasm:bundle
  pnpm wasm:bundle --output dist/edge-wasm.js --include z3,clingo
`);
    return;
  }

  const outputIndex = args.indexOf('--output');
  const includeIndex = args.indexOf('--include');

  const outputPath = outputIndex >= 0 ? args[outputIndex + 1] : 'dist/wasm-bundle';
  const includeIds = includeIndex >= 0 ? args[includeIndex + 1].split(',') : undefined;

  let modules = DEFAULT_WASM_MODULES;
  if (includeIds) {
    modules = DEFAULT_WASM_MODULES.filter(m => includeIds.includes(m.id));
  }

  await generateWasmBundle(modules, outputPath);
}

main().catch(err => {
  console.error('Fatal error:', err);
  process.exit(1);
});