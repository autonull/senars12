/**
 * README.md is generated from the sections in this directory.
 *
 * It was one 1753-line file that every change to the system touched, and it
 * drifted in two directions at once: prose no reviewer could read in a diff, and
 * projections — the NAL rule matrix — hand-maintained mirrors of a table the
 * engine already knows. So the prose lives here, one file per heading, and this
 * generator owns the two things a section file must not: the order, and every
 * value that is a projection of something else.
 *
 * A section file is its heading and its body. The `---` between top-level
 * sections is emitted here, a section's level is read from its own heading, and
 * `<!-- name -->` is a directive replaced by the generator that owns it. The rest
 * is gates — a section not in `ORDER`, a link that does not resolve, a
 * `pnpm <script>` package.json no longer declares — because each of those is a
 * README that is wrong in a way no reviewer can see.
 */
