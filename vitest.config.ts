// Plugin to normalize imports: remove trailing slashes
const normalizeImportsPlugin = {
  name: 'normalize-imports',
  enforce: 'pre' as const,
  resolveId(id, importer) {
    if (id.endsWith('/') && !id.endsWith('//')) {
      return id.slice(0, -1);
    }
    return null;
  },
};

