/** Generate completions for a specific shell. */
async function generateCompletions(shell: 'bash' | 'zsh' | 'fish' | 'powershell'): Promise<string> {
  const commands = listCommands();
  const commandMap = new Map<string, { description: string; subcommands?: string[] }>();

  for (const cmd of commands) {
    const mod = getCommand(cmd);
    const description = mod?.sections[0]?.lines[0]?.replace(/^  /, '') ?? '';
    const subcommands: string[] = [];
    if (mod?.subcommands) {
      for (const [name, subMod] of mod.subcommands) {
        const subDesc = subMod.sections[0]?.lines[0]?.replace(/^  /, '') ?? '';
        subcommands.push(`${name}  # ${subDesc}`);
      }
    }
    commandMap.set(cmd, { description, subcommands: subcommands.length > 0 ? subcommands : undefined });
  }

  const globalFlags = [
    '-h, --help',
    '-v, --version',
    '--json',
    '--quiet',
    '--verbose',
    '-p, --profile <kind>',
    '--web-ui',
    '--port <number>',
  ];

  switch (shell) {
    case 'bash':
      return generateBash(commandMap, globalFlags);
    case 'zsh':
      return generateZsh(commandMap, globalFlags);
    case 'fish':
      return generateFish(commandMap, globalFlags);
    case 'powershell':
      return generatePowerShell(commandMap, globalFlags);
    default:
      throw new Error(`Unknown shell: ${shell}`);
  }
}

function generateBash(
  commandMap: Map<string, { description: string; subcommands?: string[] }>,
  globalFlags: string[]
): string {
  const commandsArray = Array.from(commandMap.entries())
    .map(([cmd, { description }]) => `${cmd}:${description}`)
    .join(' ');

  const globalFlagsArray = globalFlags.join(' ');

  return `# senars bash completions
# Generated by \`senars completion --shell bash\`

_senars() {
  local cur prev words cword
  _init_completion || return

  local commands=(${commandsArray})
  local global_flags=(${globalFlagsArray})

  if [[ \${cword} -eq 1 ]]; then
    COMPREPLY=(\$(compgen -W "\${commands[*]}" -- "\${cur}"))
    return 0
  fi

  # For subcommands, just offer global flags (simpler approach)
  COMPREPLY=(\$(compgen -W "\${global_flags[*]}" -- "\${cur}"))
}

complete -F _senars senars
`;
}

function generateZsh(
  commandMap: Map<string, { description: string; subcommands?: string[] }>,
  globalFlags: string[]
): string {
  let output = `# senars zsh completions
# Generated by \`senars completion --shell zsh\`

#compdef senars

_senars() {
  local -a commands
  local -a global_flags
  local -a subcommands

  commands=(`;

  for (const [cmd, { description }] of commandMap) {
    output += `\n    "${cmd}:${description}"`;
  }

  output += `
  )

  global_flags=(`;

  for (const flag of globalFlags) {
    output += `\n    "${flag}"`;
  }

  output += `
  )

  _arguments -C \\
    "\${global_flags[@]}" \\
    ": :(\$commands)" \\
    "*:: :->subcmds"

  if (( CURRENT > 2 )); then
    local cmd=\${words[2]}
    case \$cmd in`;

  for (const [cmd, { subcommands }] of commandMap) {
    if (subcommands && subcommands.length > 0) {
      output += `\n      ${cmd})`;
      output += `\n        subcommands=(`;
      for (const sub of subcommands) {
        output += `\n          "${sub}"`;
      }
      output += `
        )
        _arguments "*:: :(\$subcommands)"
        ;;`;
    }
  }

  output += `
    esac
  fi
}

_senars "\$@"
`;

  return output;
}

function generateFish(
  commandMap: Map<string, { description: string; subcommands?: string[] }>,
  globalFlags: string[]
): string {
  let output = `# senars fish completions
# Generated by \`senars completion --shell fish\`

complete -c senars -f -n "__fish_use_subcommand"
`;

  for (const [cmd, { description, subcommands }] of commandMap) {
    output += `complete -c senars -n "__fish_seen_subcommand_from ${cmd}" -f -a "${subcommands?.join(' ') || ''}"\n`;
    for (const flag of globalFlags) {
      output += `complete -c senars -n "__fish_seen_subcommand_from ${cmd}" -l "${flag.replace(/^-+/, '')}"\n`;
    }
    if (subcommands && subcommands.length > 0) {
      for (const sub of subcommands) {
        const subName = sub.split(' ')[0];
        output += `complete -c senars -n "__fish_seen_subcommand_from ${cmd} ${subName}" -f\n`;
      }
    }
  }

  // Global completions (no subcommand)
  output += '\n# Global flags\n';
  for (const flag of globalFlags) {
    output += `complete -c senars -n "not __fish_seen_subcommand_from *" -l "${flag.replace(/^-+/, '')}"\n`;
  }

  output += '\n# Top-level commands\n';
  for (const [cmd, { description }] of commandMap) {
    output += `complete -c senars -n "not __fish_seen_subcommand_from *" -a "${cmd}" -d "${description}"\n`;
  }

  return output;
}

function generatePowerShell(
  commandMap: Map<string, { description: string; subcommands?: string[] }>,
  globalFlags: string[]
): string {
  let output = `# senars PowerShell completions
# Generated by \`senars completion --shell powershell\`

Register-ArgumentCompleter -Native -CommandName senars -ScriptBlock {
  param(\$wordToComplete, \$commandAst, \$cursorPosition)
  \$commands = @(`;

  for (const [cmd, { description }] of commandMap) {
    output += `\n    @{ Name = "${cmd}"; Description = "${description}" }`;
  }

  output += `
  )

  \$globalFlags = @(`;

  for (const flag of globalFlags) {
    output += `\n    "${flag}"`;
  }

  output += `
  )

  \$tokens = \$commandAst.CommandElements | Where-Object { \$_.Value -notmatch "^--" }
  \$tokenCount = \$tokens.Count

  if (\$tokenCount -eq 1) {
    \$commands | Where-Object { \$_.Name -like "\$wordToComplete*" } | ForEach-Object {
      [System.Management.Automation.CompletionResult]::new(\$_.Name, \$_.Name, "ParameterValue", \$_.Description)
    }
    \$globalFlags | Where-Object { \$_ -like "\$wordToComplete*" } | ForEach-Object {
      [System.Management.Automation.CompletionResult]::new(\$_, \$_, "ParameterValue", "")
    }
    return
  }

  \$subCmd = \$tokens[1].Value
  \$subCommands = switch (\$subCmd) {`;

  for (const [cmd, { subcommands }] of commandMap) {
    if (subcommands && subcommands.length > 0) {
      output += `\n    "${cmd}" {`;
      for (const sub of subcommands) {
        const subName = sub.split(' ')[0];
        const subDesc = sub.split('#')[1]?.trim() || '';
        output += `\n      @{ Name = "${subName}"; Description = "${subDesc}" }`;
      }
      output += `
    }`;
    }
  }

  output += `
  }

  if (\$subCommands) {
    \$subCommands | Where-Object { \$_.Name -like "\$wordToComplete*" } | ForEach-Object {
      [System.Management.Automation.CompletionResult]::new(\$_.Name, \$_.Name, "ParameterValue", \$_.Description)
    }
  }
  \$globalFlags | Where-Object { \$_ -like "\$wordToComplete*" } | ForEach-Object {
    [System.Management.Automation.CompletionResult]::new(\$_, \$_, "ParameterValue", "")
  }
}
`;

  return output;
}

export async function main(flags: CommonFlags): Promise<void> {
  const { parseFlags } = await import('@senars/util/cli');
  const args = parseFlags();

  let shell = args.str('--shell', '');
  const outputPath = args.str('--output', '');

  // Auto-detect shell if not specified
  if (!shell) {
    const userShell = process.env.SHELL ?? '';
    if (userShell.includes('zsh')) shell = 'zsh';
    else if (userShell.includes('fish')) shell = 'fish';
    else if (userShell.includes('bash')) shell = 'bash';
    else if (process.platform === 'win32') shell = 'powershell';
    else shell = 'bash';
  }

  if (!['bash', 'zsh', 'fish', 'powershell'].includes(shell)) {
    console.error(`Unknown shell: ${shell}. Supported: bash, zsh, fish, powershell`);
    process.exit(1);
  }

  const completions = await generateCompletions(shell as 'bash' | 'zsh' | 'fish' | 'powershell');

  if (outputPath) {
    const { writeFileSync } = await import('node:fs');
    writeFileSync(outputPath, completions, 'utf8');
    console.error(`Completions written to ${outputPath}`);
  } else {
    console.log(completions);
  }
}